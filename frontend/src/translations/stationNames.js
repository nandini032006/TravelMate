// Suffixes to strip before lookup
const _STRIP_SUFFIXES = [
  ' metro station', ' bus stop', ' bus stand', ' railway station',
  ' station', ' stop', ' depot', ' terminal', ' junction',
  ' x roads', ' x-roads', ' cross roads', ' circle', ' flyover',
]

function _clean(name) {
  // Strip "(METRO stop)", "(BUS stop)", "(MMTS stop)" etc. added by autocomplete
  let s = name.replace(/\s*\([^)]*\bstop\b[^)]*\)/gi, '').trim()
  // Strip ", Hyderabad" and anything after comma (from geocoding labels)
  s = s.split(',')[0].trim()
  return s
}

export function translateStopName(name) {
  if (!name) return name
  const trimmed = name.trim()
  const cleaned = _clean(trimmed)

  // Check both the original and cleaned versions
  for (const candidate of [trimmed, cleaned]) {
    // 1. Exact match
    if (STATION_NAMES_TE[candidate]) return STATION_NAMES_TE[candidate]

    // 2. Case-insensitive exact match
    const lower = candidate.toLowerCase()
    for (const [key, val] of Object.entries(STATION_NAMES_TE)) {
      if (key.toLowerCase() === lower) return val
    }

    // 3. Strip common suffixes and retry
    for (const suffix of _STRIP_SUFFIXES) {
      if (lower.endsWith(suffix)) {
        const stripped = candidate.slice(0, candidate.length - suffix.length).trim()
        if (STATION_NAMES_TE[stripped]) return STATION_NAMES_TE[stripped]
        const strippedLower = stripped.toLowerCase()
        for (const [key, val] of Object.entries(STATION_NAMES_TE)) {
          if (key.toLowerCase() === strippedLower) return val
        }
      }
    }

    // 4. Starts-with match
    for (const [key, val] of Object.entries(STATION_NAMES_TE)) {
      if (
        lower.startsWith(key.toLowerCase() + ' ') ||
        lower.startsWith(key.toLowerCase() + '-') ||
        lower.startsWith(key.toLowerCase() + ',')
      ) return val
    }
  }

  // Return cleaned name (at least remove the "(METRO stop)" junk)
  return cleaned || trimmed
}

// ── Reverse mapping: Telugu → English (for Telugu-input search) ───────────────
const _TE_TO_EN = Object.fromEntries(
  Object.entries(STATION_NAMES_TE).map(([en, te]) => [te, en])
)

// Detect whether a string contains Telugu characters
export function isTeluguText(str) {
  return /[ఀ-౿]/.test(str)
}

// Convert a Telugu query to its English equivalent for backend search.
// Falls back to the original string if no match found.
export function teQueryToEn(query) {
  if (!query || !isTeluguText(query)) return query
  const trimmed = query.trim()
  if (_TE_TO_EN[trimmed]) return _TE_TO_EN[trimmed]
  // Partial prefix match (e.g. user typed partial Telugu name)
  for (const [te, en] of Object.entries(_TE_TO_EN)) {
    if (te.startsWith(trimmed)) return en
  }
  return query
}

// Translate the autocomplete type string to Telugu
export function translateType(type, t) {
  if (!type) return type
  const lower = type.toLowerCase()
  if (lower === 'metro') return t.metro || 'మెట్రో'
  if (lower === 'bus')   return t.bus   || 'బస్సు'
  if (lower === 'mmts')  return t.mmts  || 'ఎంఎంటీఎస్'
  if (lower === 'walk')  return t.walk  || 'నడక'
  if (lower === 'auto')  return t.auto  || 'ఆటో'
  return type
}
